"""Write sw.js: the offline cache list (every file the game needs) and a version hash of their contents.

Run after changing any game file, before publishing: python tools/build_sw.py
A new version makes installed copies (iPhone home screen) download the update on next launch.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
core = ["index.html", "style.css", "game.js", "voice/index.js", "manifest.webmanifest"]
files = core + sorted(str(p.relative_to(ROOT)).replace("\\", "/") for p in (ROOT / "assets").glob("*") if p.is_file())
files += sorted(str(p.relative_to(ROOT)).replace("\\", "/") for p in (ROOT / "icons").glob("*.png"))
lines = json.loads((ROOT / "voice" / "lines.json").read_text(encoding="utf-8"))
files += sorted({"voice/" + f for f in lines.values()})
h = hashlib.sha256()
for f in files:
    h.update(f.encode())
    h.update((ROOT / f).read_bytes())
version = h.hexdigest()[:12]
precache = ["./"] + [f for f in files if f != "index.html"]

sw = f"""// Generated by tools/build_sw.py. Do not edit by hand.
const VERSION = '{version}';
const CACHE = 'mochi-' + VERSION;
const FONTS = 'mochi-fonts';
const PRECACHE = {json.dumps(precache, indent=0)};

self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('mochi-') && k !== CACHE && k !== FONTS).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === location.origin) {{
    // Game files: from the offline copy first, network only for anything not cached.
    e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then(r => r || fetch(req)));
  }} else if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {{
    // Fonts: use the saved copy, refresh it in the background when online.
    e.respondWith(caches.open(FONTS).then(c => c.match(req).then(hit => {{
      const net = fetch(req).then(r => {{ if (r.ok || r.type === 'opaque') c.put(req, r.clone()); return r; }}).catch(() => hit);
      return hit || net;
    }})));
  }}
}});
"""
(ROOT / "sw.js").write_text(sw, encoding="utf-8")
print(f"sw.js version {version}, {len(precache)} files")
